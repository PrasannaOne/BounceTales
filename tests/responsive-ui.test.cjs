const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
const game=fs.readFileSync(path.join(root,'game.js'),'utf8');
assert.match(html,/id="game-controls"/);
assert.match(html,/id="keyboard-hint"/);
assert.match(html,/data-settings-tab="game"/);
assert.match(html,/data-settings-tab="about"/);
assert.match(html,/id="settings-about-pane"[\s\S]*Made by Prasanna ❤️/);
assert.match(html,/id="reset-game"/);
assert.match(html,/github\.com\/PrasannaOne\/BounceTales/,'About visibly names the repository');
assert.match(html,/class="share-icon"/,'header has a conventional connected-node share icon');
assert.doesNotMatch(html,/share-label/,'share control is icon-only');
assert.match(css,/min-width:820px/,'desktop grid layout exists');
assert.match(css,/max-height:620px\) and \(orientation:landscape\)/,'landscape phone layout exists');
assert.match(css,/#app:not\(\[data-mode="play"\]\) \.controls,/,'touch controls are hidden in menus');
assert.match(css,/\.settings-panel\{[^}]*overflow:hidden/s,'settings panel does not scroll');
assert.match(css,/\.special-control-row\{height:[^}]*display:flex/,'star occupies a separate lower row, not an overlay');
assert.match(css,/\.game-wrap\{margin-bottom:clamp\(/,'game viewport is separated from the thumb controls for visibility');
assert.match(css,/\.header-btn\.share-only\{width:64px/,'share button is compact and icon-only');
assert.match(css,/\.settings-panel\{[^}]*max-height:min\(/s,'settings panel respects screen height');
assert.match(game,/function pollGamepad\(\)/,'standard gamepad polling exists');
assert.match(game,/changeBookPage\(dx<0\?1:-1\)/,'chapter book supports swipe navigation');
assert.match(game,/function syncSceneChrome\(\)/,'scene state updates responsive UI');
assert.match(game,/cameraSpring\.update\(/,'gameplay uses the source-style camera spring');
console.log('Responsive UI: phone portrait/landscape, desktop, menu touch, compact options, keyboard/gamepad and swipe hooks passed');

const v18=css.slice(css.lastIndexOf('V18: thumb-control clearance'));
assert.match(v18,/\.special-control-row \.special\s*\{[^}]*width:\s*42px/s,'star grows slightly on short phone screens');
assert.match(v18,/\.special-control-row\s*\{\s*height:\s*39px/s,'star grows inside the same reserved control row');
assert.match(v18,/\.game-wrap\s*\{[^}]*margin-bottom:\s*clamp\(/s,'portrait touch controls retain a deliberate gap under the game');
assert.match(css,/html, body\s*\{[^}]*overflow:\s*hidden/s,'document remains unscrollable');
console.log('V18 layout: fixed no-scroll page, control clearance and non-expanding star row passed');
