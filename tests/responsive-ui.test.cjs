const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
const game=fs.readFileSync(path.join(root,'game.js'),'utf8');
assert.match(html,/id="game-controls"/);
assert.match(html,/id="keyboard-hint"/);
assert.match(html,/data-settings-tab="game"/);
assert.match(html,/data-settings-tab="about"/);
assert.match(html,/id="settings-about-pane"[\s\S]*Made by Prasanna ❤️/);
assert.match(html,/id="reset-game"/);
assert.match(html,/github\.com\/PrasannaOne\/BounceTales/,'About visibly names the repository');
assert.match(html,/class="share-icon"/,'header has a conventional connected-node share icon');
assert.doesNotMatch(html,/share-label/,'share control is icon-only');
assert.match(css,/min-width:\s*820px/,'large portrait screens use a two-column game/control layout');
assert.match(css,/\(orientation:\s*landscape\) and \(max-height:\s*620px\)/,'landscape phone layout exists');
assert.match(css,/#app \.controls\{display:flex;/,'touch controls remain visible across title, chapter, pause and gameplay screens');
assert.doesNotMatch(css,/#app:not\(\[data-mode="play"\]\) #game-controls\{display:none/,'no scene hides the touch controls');
assert.match(css,/\.settings-panel\{[^}]*overflow:hidden/s,'settings panel does not scroll');
assert.match(css,/\.special-control-row\{[^}]*height:[^}]*display:flex/,'star occupies a separate lower row, not an overlay');
assert.match(css,/#app\s*\{[^}]*gap:\s*12px/s,'the shell provides room between the viewport and touch controls');
assert.match(css,/\.header-btn\.share-only\s*\{[^}]*width:\s*44px/s,'share button is compact and icon-only');
assert.match(css,/\.settings-panel\{[^}]*max-height:min\(/s,'settings panel respects screen height');
assert.match(game,/function pollGamepad\(\)/,'standard gamepad polling exists');
assert.match(game,/changeBookPage\(dx<0\?1:-1\)/,'chapter book supports swipe navigation');
assert.match(game,/function syncSceneChrome\(\)/,'scene state updates responsive UI');
assert.match(game,/cameraSpring\.update\(/,'gameplay uses the source-style camera spring');
console.log('Responsive UI: phone portrait/landscape, desktop, menu touch, compact options, keyboard/gamepad and swipe hooks passed');

assert.match(css,/\.special-control-row \.special\s*\{[^}]*width:\s*clamp\(36px,10vw,44px\)/s,'the special control stays within a bounded touch target');
assert.match(css,/\.special-control-row\s*\{[^}]*height:\s*clamp\(39px,11vw,49px\)/s,'the special control reserves its own responsive row');
assert.match(css,/#app\s*\{[^}]*gap:\s*12px/s,'game and touch controls are separated by the shell gap');
assert.match(css,/html,\s*body\s*\{[^}]*overflow-x:\s*hidden/s,'horizontal overflow is clipped without trapping short screens vertically');
console.log('V54 layout: responsive special-control target, explicit game/control separation and safe viewport overflow passed');
