const assert=require('node:assert/strict');
const P=require('../src/original-progression.js');
const storage={value:null,getItem(){return this.value;},setItem(k,v){this.value=v;},removeItem(){this.value=null;}};
let save=P.create();
assert.equal(P.isUnlocked(save,0),true);
assert.equal(P.isUnlocked(save,1),false);
let result=P.complete(save,0,30,42000);
assert.equal(result.nextLevel,1);assert.ok(P.isUnlocked(save,1));assert.equal(result.seconds,42);
assert.equal(P.isUnlocked(save,4),false,'bonus chapter stays locked below 60 total eggs');
// Complete chapters with enough eggs to unlock the original bonus threshold.
P.complete(save,1,30,50000);P.complete(save,2,30,60000);
assert.equal(P.totalEggs(save),90);
P.complete(save,3,30,55000);
assert.equal(P.isUnlocked(save,4),true,'Secret Stalkway unlocks at 60 total eggs');
P.complete(save,4,30,70000);
assert.equal(P.isUnlocked(save,5),true,'regular progression skips the bonus page');
assert.equal(save.unlockedForme,1,'Bumpy form unlocks after level 4 (index 3)');
for(let i=5;i<=8;i++)P.complete(save,i,30,45000);
assert.equal(save.unlockedForme,2,'Wolly form unlocks after level 9 (index 8)');
P.complete(save,9,30,70000);
for(let i=10;i<=13;i++)P.complete(save,i,30,45000);
assert.equal(P.isUnlocked(save,14),true,'Fantastic Fair unlocks at 400 total eggs');
assert.equal(P.nextRegular(3),5);assert.equal(P.nextRegular(8),10);assert.equal(P.nextRegular(13),-1);
P.save(storage,save);const restored=P.load(storage);
assert.equal(restored.records[3].eggs,30);assert.equal(restored.unlockedForme,2);assert.equal(restored.selected,0);
const wiped=P.reset(storage);assert.equal(P.isUnlocked(wiped,1),false);assert.equal(storage.value,null);
console.log('Progression: original bonus thresholds, stage unlock order, form unlocks, score/time records and persistent save/reset passed');
