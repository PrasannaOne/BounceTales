const assert=require('node:assert/strict');
const api=require('../src/original-input-map.js');
const K=api.KEY;
assert.equal(api.normalizeJavaMEKey(-7),K.SOFTKEY_RIGHT);
assert.equal(api.normalizeJavaMEKey(-6),K.SOFTKEY_LEFT);
assert.equal(api.normalizeJavaMEKey(-5),K.SOFTKEY_MIDDLE);
assert.equal(api.normalizeJavaMEKey(42),K.STAR);
assert.equal(api.normalizeJavaMEKey(35),K.POUND);
assert.equal(api.normalizeJavaMEKey(50,null,2),K.UP);
assert.equal(api.normalizeJavaMEKey(52,null,2),K.LEFT);
assert.equal(api.normalizeJavaMEKey(53,null,2),K.SOFTKEY_MIDDLE);
assert.equal(api.browserKeyId('ArrowLeft'),K.LEFT);
assert.equal(api.browserKeyId('ArrowRight'),K.RIGHT);
assert.equal(api.browserKeyId('a'),K.LEFT);
assert.equal(api.browserKeyId('D'),K.RIGHT);
assert.equal(api.browserKeyId('w'),K.UP);
assert.equal(api.browserKeyId(' '),K.SOFTKEY_MIDDLE);
assert.equal(api.browserKeyId('Shift'),K.STAR);
assert.equal(api.browserKeyId('q'),K.STAR);
assert.equal(api.browserKeyId('Enter'),K.SOFTKEY_MIDDLE);
assert.equal(api.browserKeyId('Escape'),K.SOFTKEY_RIGHT);
assert.equal(api.browserKeyId('*'),K.STAR);
for(let digit=1;digit<=9;digit++)assert.equal(api.browserKeyId(String(digit)),-1);
const state=new api.OriginalInputState();
state.press(K.LEFT);state.press(K.LEFT);state.press(K.RIGHT);state.press(K.SOFTKEY_MIDDLE);
assert.equal(state.isHeld(K.LEFT),true);
assert.deepEqual(state.drainEdges(),[K.LEFT,K.RIGHT,K.SOFTKEY_MIDDLE]);
assert.deepEqual(state.gameHeld(),{left:true,right:true,jump:true,up:false,down:false});
state.release(K.LEFT);state.release(K.RIGHT);state.release(K.SOFTKEY_MIDDLE);
assert.deepEqual(state.gameHeld(),{left:false,right:false,jump:false,up:false,down:false});
console.log('Input: original mapping, touchscreen, PC keyboard and star mappings passed');
