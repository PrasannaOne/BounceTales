const assert=require('node:assert/strict');
const {start,update,frame,frameDurationMs}=require('../src/original-sprite-animation.js');
assert.equal(frameDurationMs,150,'original sprite frame duration should be 150 ms');
const state=start([[0,0,118],[0,0,334],[0,0,342],[0,0,999]]);
assert.deepEqual(state.slots.map(s=>s?.imageId??null),[485,474,480,null],'the three original sprite IDs should map to their original event animation maps');
assert.equal(frame(state,0,300).frame,2,'indefinite image-485 animation should follow the 150 ms frame cadence');
assert.equal(frame(state,2,450).frame,3,'indefinite image-480 animation should use elapsed game time');
assert.equal(frame(state,1,0).alpha,1,'finite image-474 sequence should begin opaque');
update(state,750);
assert.equal(frame(state,1,750).alpha,0,'image-474 sequence should begin its fade-in as the initial 750 ms timer expires');
update(state,750);
assert.equal(frame(state,1,1500).alpha,0.5,'image-474 should fade in over the following 1500 ms');
update(state,750);
assert.equal(frame(state,1,2250).alpha,1,'image-474 sequence should reach full opacity at its terminal fade time');
update(state,1);
assert.equal(frame(state,1,2251),null,'the finite original sprite animation should reset after its terminal timer');
console.log('Original sprite animation: 118→485, 334→474 and 342→480 mappings, 150 ms frames and 750+1500 ms fade sequence passed');
