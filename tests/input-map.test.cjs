const assert=require('node:assert/strict');
const api=require('../src/original-input-map.js');
const K=api.KEY;
assert.equal(api.normalizeJavaMEKey(-7),K.SOFTKEY_RIGHT);
assert.equal(api.normalizeJavaMEKey(-6),K.SOFTKEY_LEFT);
assert.equal(api.normalizeJavaMEKey(-5),K.SOFTKEY_MIDDLE);
assert.equal(api.normalizeJavaMEKey(42),K.STAR);
assert.equal(api.normalizeJavaMEKey(35),K.POUND);
assert.equal(api.normalizeJavaMEKey(50,null,2),K.UP);
assert.equal(api.normalizeJavaMEKey(52,null,2),K.LEFT);
assert.equal(api.normalizeJavaMEKey(53,null,2),K.SOFTKEY_MIDDLE);
assert.equal(api.browserKeyId('ArrowUp'),K.UP);
assert.equal(api.browserKeyId('Enter'),K.SOFTKEY_MIDDLE);
assert.equal(api.browserKeyId('*'),K.STAR);
assert.equal(api.browserKeyId('#'),K.POUND);
for(let digit=1;digit<=9;digit++)assert.equal(api.browserKeyId(String(digit)),-1,'touch/keyboard layout omits keypad digits');
const state=new api.OriginalInputState();
state.press(K.LEFT);state.press(K.LEFT);
assert.equal(state.isHeld(K.LEFT),true);
assert.deepEqual(state.drainEdges(),[K.LEFT]);
state.release(K.LEFT);assert.equal(state.isHeld(K.LEFT),false);
console.log('Input: Nokia softkeys, D-pad, * and # mappings passed');
