'use strict';
const assert=require('node:assert/strict');
const {ParticleSystem}=require('../src/game-particles.js');
const system=new ParticleSystem(()=>0.75);
system.emitOriginalSpriteFragments(24,36,-7,-42);
assert.equal(system.items.length,24,'original emitter must create 24 particles');
assert.ok(system.items.every(p=>[390,414,396].includes(p.spriteId)),'particles must use the three original source sprite IDs');
assert.ok(system.items.every(p=>Math.abs(p.x-33)<1e-9&&Math.abs(p.y-18)<1e-9),'particles must spawn inside the transformed inset source bounds');
assert.ok(system.items.every(p=>p.life>=1.53&&p.life<=2.55),'source 2040 ± 510 ms life range must be retained');
const first=system.items[0],startX=first.x,startY=first.y;
system.update(.016);
assert.notEqual(first.y,startY,'source fragments should move in the original emission direction');
system.update(.784);
assert.equal(first.frame,1,'five-frame source fragments should advance over their original lifetime');
let draws=0;
const fake={save(){},restore(){},set globalAlpha(v){}};
system.draw(fake,p=>p,1,()=>draws++);
assert.equal(draws,24,'source fragments should render through the original image-map callback');
system.update(2);
assert.equal(system.items.length,0,'source fragments should expire rather than persist');
console.log('Original sprite fragments: source particle count, sprite family, spawn bounds, lifetime, animation, motion and rendering passed');
