'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
assert.match(html, /style\.css\?v=47/);
assert.match(html, /src\/[^"']+\?v=47/);
assert.match(html, /game\.js\?v=47/);
assert.match(html, /sw\.js\?v=47/);
assert.doesNotMatch(html, /\?v=32\b/, 'index.html must not retain old versioned assets');
assert.match(sw, /CACHE_NAME\s*=\s*'bounce-tales-v47'/);
assert.doesNotMatch(sw, /\?v=32\b/, 'service worker shell must not retain old versioned assets');
assert.match(html, /class="header-btn heart-link"/, 'red heart header link is preserved');
console.log('V42 cache-bust: index.html and service-worker shell use v42; red heart header link preserved');
