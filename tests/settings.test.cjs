const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const js=fs.readFileSync(path.join(__dirname,'../game.js'),'utf8');
const fps=html.match(/<select id="fps-mode">([\s\S]*?)<\/select>/)?.[1]||'';
for(const value of ['auto','30','60','90','120'])assert.match(fps,new RegExp('value="'+value+'"'));
assert.match(html,/id="smooth-motion" type="checkbox"/);
assert.match(js,/localStorage\.getItem\('bounce-smooth-motion'\)==='true'/);
assert.match(js,/function applySmoothMotion\(value\)/);
assert.match(js,/renderAlpha=smoothMotion\?timing\.alpha:1/);
const timing=fs.readFileSync(path.join(__dirname,'../src/game-timing.js'),'utf8');
assert.match(timing,/const FIXED_TICK_RATE=60/);
assert.match(js,/\['auto','30','60','90','120'\]/);
assert.match(html,/Made by Prasanna ❤️/);
assert.match(html,/https:\/\/t\.me\/prasannaone/);
assert.match(html,/https:\/\/github\.com\/PrasannaOne\/BounceTales/);
assert.match(js,/https:\/\/prasannaone\.github\.io\/BounceTales\//);
console.log('Settings: Auto/30/60/90/120 FPS cap and persisted Smooth Motion OFF-by-default rendering toggle validated');
