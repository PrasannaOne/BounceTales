const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const game=fs.readFileSync(path.join(root,'game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const atlas=JSON.parse(fs.readFileSync(path.join(root,'src','sprite-atlas.json'),'utf8'));
for(const id of [101,102,103])assert.ok(atlas.sprites.some(s=>s.sprite_id===id),`original HUD sprite ${id} exists`);
assert.match(game,/function drawOriginalGameplayHud\(\)/);
assert.match(game,/drawImageMap\(102,10,8\)/,'original egg icon is used');
assert.match(game,/drawImageMap\(101,39,8\)/,'original score separator/icon is used');
assert.match(game,/drawImageMap\(103,142,8\)/,'original clock icon is used');
assert.match(game,/drawOriginalGameplayHud\(\);/,'HUD renders with gameplay and paused/completed gameplay scene');
assert.match(game,/target\.strokeText\(String\(text\),x,y,214\)/,'high-DPI text receives a dark outline');
assert.match(game,/function drawJ2MEPanel\(/,'J2ME-style square panel renderer exists');
assert.match(game,/drawImageMap\(89,/,'original atlas ornament is used in menu panels');
assert.match(game,/drawImageMap\(10,/,'original atlas highlight strip is used for focused menu rows');
assert.doesNotMatch(game,/ctx\.roundRect\(/,'modern rounded-card menu treatment is removed');
assert.match(game,/function canvasMenuButton\(/,'menu rows use the shared MIDP-style renderer');
assert.match(game,/canvasMenuButton\('CONTINUE',[^\\n]*'resume'/);
assert.match(game,/canvasMenuButton\('RESTART',[^\n]*'restart'/);
assert.match(game,/canvasMenuButton\('OPTIONS',[^\n]*'options'/);
assert.match(game,/canvasMenuButton\('MAIN MENU',[^\n]*'quit-confirm'/);
assert.match(html,/style\.css\?v=45/);
assert.match(html,/game\.js\?v=45/);
assert.match(sw,/CACHE_NAME\s*=\s*'bounce-tales-v45'/);
console.log('V45 J2ME menu: original atlas decoration/highlight, square MIDP rows, crisp HUD text, and pause actions verified');
