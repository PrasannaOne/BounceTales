const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const game=fs.readFileSync(path.join(__dirname,'..','game.js'),'utf8');
assert.match(html,/<canvas id="game" width="240" height="320"/);
assert.match(html,/<div class="overlay game-scene" id="menu"/);
assert.match(html,/<div class="overlay game-scene" id="level-screen"/);
assert.match(html,/id="level-prev"/);assert.match(html,/id="level-next"/);
assert.match(html,/id="pause-layer"/);assert.match(html,/id="complete-layer"/);
assert.doesNotMatch(html,/id="level-select"|<select[^>]+level/i,'no developer-style level dropdown');
assert.match(html,/id="share-site"[^>]+aria-label="Share Bounce Tales"/);
assert.match(html,/id="open-settings"[^>]+aria-label="Settings"/);
assert.match(html,/id="pause-mini"/);
assert.match(game,/function drawOriginalChapterBook\(\)/);
assert.match(game,/drawImageMap\(1,120,70\)/,'title scene uses the original Bounce Tales title logo resource');
assert.doesNotMatch(game,/menuText\('BOUNCE TALES',120,93/,'no duplicate text is painted over the original logo');
assert.match(game,/function moveCanvasMenuFocus\(/,'canvas menu supports keyboard/gamepad focus movement');
assert.match(game,/drawImageMap\(331,120,160\)/,'uses the original JAR book-frame compound sprite');
assert.match(game,/function drawCanvasChapterBook\(\)[\s\S]*?drawImageMap\(COVER_IDS\[selectedLevelIndex\],120,137\)/,'chapter cover is painted on the main 240x320 canvas');
for(const name of ['drawCanvasTitle','drawCanvasPause','drawCanvasComplete','drawCanvasGuide','drawCanvasScores','drawCanvasOptions'])assert.match(game,new RegExp('function '+name+'\\('),name+' is a canvas scene');
assert.match(game,/function bindCanvasMenu\(\)[\s\S]*?pointerdown[\s\S]*?pointerup/,'canvas menu uses pointer input');
assert.match(game,/else if\(action==='scores'\)/);assert.match(game,/else if\(action==='options'\)/);
assert.match(game,/canvasMenuButton\('MAIN MENU',[^\n]*'title'/,'pause screen has a Main Menu action');
assert.match(game,/canvasMenuButton\('RESTART LEVEL'/,'pause screen has a level restart action');
console.log('Canvas menu flow: title, chapter book, scores, options, guide, pause and chapter results are drawn on the game canvas');
